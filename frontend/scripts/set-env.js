// Writes src/environments/environment.prod.ts at build time from API_BASE_URL (or BACKEND_URL).
// The API URL is fixed per build; it cannot be changed from the browser.
const fs = require('fs');
const path = require('path');

const targetPath = path.resolve(__dirname, '../src/environments/environment.prod.ts');
const rawUrl = process.env.API_BASE_URL || process.env.BACKEND_URL || 'https://ms-shared-data-platform.onrender.com';
const cleanUrl = rawUrl.trim().replace(/\/$/, '');

const envConfigFile = `// Generated by scripts/set-env.js during the production build.
export const environment = {
  production: true,
  apiBaseUrl: '${cleanUrl}',
  appName: 'Compliance Hub',
  version: '1.0.0',
  enableDebugTools: false,
};
`;

fs.writeFileSync(targetPath, envConfigFile, { encoding: 'utf8' });
console.log(`[set-env] Injected production apiBaseUrl: ${cleanUrl}`);
